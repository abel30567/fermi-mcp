// Writes .vitepress/theme/tokens.css from design/tokens.json. Run: node design/build-tokens.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const here = new URL('.', import.meta.url)
const t = JSON.parse(readFileSync(new URL('tokens.json', here), 'utf8'))
const kebab = (s) => s.replace(/[A-Z0-9]+/g, (m) => `-${m.toLowerCase()}`)
const strip = (o) => Object.entries(o).filter(([k]) => !k.startsWith('$'))

function modeVars(mode) {
	const out = []
	for (const [k, v] of strip(t.surface[mode])) out.push(`--fx-${kebab(k)}: ${v};`)
	for (const [tone, parts] of strip(t.tone[mode]))
		for (const [k, v] of Object.entries(parts)) out.push(`--fx-${tone}-${kebab(k)}: ${v};`)
	const s = t.site[mode]
	out.push(
		`--vp-c-brand-1: ${s.brand1};`,
		`--vp-c-brand-2: ${s.brand2};`,
		`--vp-c-brand-3: ${s.brand3};`,
		`--vp-c-brand-soft: ${s.brandSoft};`,
	)
	if (s.bg)
		out.push(
			`--vp-c-bg: ${s.bg};`,
			`--vp-c-bg-alt: ${s.bgAlt};`,
			`--vp-c-bg-soft: ${s.bgSoft};`,
			`--vp-c-bg-elv: ${s.bgElv};`,
		)
	return out
}

const root = [
	...strip(t.brand).map(([k, v]) => `--fx-brand-${kebab(k)}: ${v};`),
	...strip(t.font).map(([k, v]) => `--fx-font-${k}: ${v};`),
	...strip(t.type).map(([k, v]) => `--fx-text-${kebab(k)}: ${v}px;`),
	...strip(t.radius).map(([k, v]) => `--fx-radius-${k}: ${v}px;`),
	...strip(t.stroke).map(([k, v]) => `--fx-stroke-${k}: ${v}px;`),
	...modeVars('light'),
]

const css = `/* Generated by design/build-tokens.mjs from design/tokens.json. Do not edit by hand. */
:root {
${root.map((l) => `\t${l}`).join('\n')}
}

.dark {
${modeVars('dark')
	.map((l) => `\t${l}`)
	.join('\n')}
}
`
writeFileSync(new URL('../.vitepress/theme/tokens.css', here), css)
console.log('wrote .vitepress/theme/tokens.css')
